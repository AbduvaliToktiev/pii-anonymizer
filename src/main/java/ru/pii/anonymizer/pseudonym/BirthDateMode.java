package ru.pii.anonymizer.pseudonym;

/** Что модель узнаёт о дате рождения. */
public enum BirthDateMode {

    /** Только метка вида {@code [BIRTHDATE_n]}: о дате неизвестно ничего. */
    DATE,

    /**
     * Метка с возрастом в полных годах на сегодня: {@code [BIRTHDATE_n_AGE41]}. Модель может отвечать
     * на вопросы о возрасте, но точной даты не видит. Если дату не удалось разобрать (например,
     * записан только год), метка выдаётся без возраста.
     */
    AGE
}
