package ru.pii.anonymizer.detect;

import java.util.Locale;
import java.util.Set;
import java.util.regex.Pattern;

/** Похоже ли слово с заглавной буквы на фамилию: общие правила для детекторов ФИО. */
final class Surnames {

    /** Окончания фамилий с падежными окончаниями: Петров, Петрова, Петровым, Сидоровой, Ковальчук, Шевченко… */
    private static final Pattern ENDING = Pattern.compile(
            "(?:ов|ев|ёв|ин|ын|ск|цк|енко|ко|ук|юк|чук|ич|ых|их|ян|янц|дзе|швили|ман|ец|ак|ик|ер)"
                    + "(?:а|у|ым|ом|е|ой|ую|ая|ий|ого|ому|им|ых|ою|ей|ы|и)?$");

    /**
     * Слова с заглавной буквы рядом с именем или инициалами, которые фамилией не бывают.
     * Нужны прежде всего те, что похожи на фамилию по окончанию: «Гражданин И.И. Иванов».
     */
    private static final Set<String> NOT_SURNAMES = Set.of(
            "сотрудник", "сотрудника", "сотруднику", "сотрудником", "сотрудница", "сотруднице", "сотрудницу",
            "работник", "работника", "работнику", "руководитель", "начальник", "начальника", "заместитель",
            "менеджер", "менеджера", "инженер", "инженера", "разработчик", "разработчика", "тестировщик",
            "тестировщика", "программист", "бухгалтер", "бухгалтера", "специалист", "водитель", "клиент",
            "клиента", "пациент", "пациента", "студент", "студента", "дизайнер", "аналитик", "техник",
            "механик", "юрист", "уважаемый", "уважаемая", "уважаемой", "уважаемому", "дорогой", "дорогая",
            "коллега", "привет", "здравствуйте", "исполнитель", "ответственный",
            "заказчик", "подрядчик", "собственник", "владелец", "директор", "директора", "директору",
            "пенсионер", "пенсионера", "пенсионеру", "пенсионерка", "пенсионерки", "пенсионерке",
            "гражданин", "гражданина", "гражданину", "гражданином", "гражданине",
            "гражданка", "гражданки", "гражданке", "гражданку", "гражданкой",
            "граждане", "граждан", "гражданам",
            "господин", "господина", "господину", "господином", "господине",
            "госпожа", "госпожи", "госпоже", "госпожу", "госпожой",
            "товарищ", "товарища", "товарищу", "товарищем", "товарище",
            "мужчина", "мужчины", "мужчине", "мужчину", "мужчиной",
            "женщина", "женщины", "женщине", "женщину", "женщиной",
            "рядовой", "рядового", "рядовому", "рядовым", "рядовом",
            "старшина", "старшины", "старшине", "старшину", "старшиной",
            "сын", "сына", "сыну", "сыном", "сыне",
            "внук", "внука", "внуку", "внуком", "внуке");

    private Surnames() {
    }

    /** Слово из списка исключений: рядом с именем стоит, но фамилией не бывает. */
    static boolean isNever(String word) {
        return NOT_SURNAMES.contains(word.toLowerCase(Locale.ROOT));
    }

    /** Не исключение и кончается как фамилия; для двойной фамилии смотрится последняя часть. */
    static boolean looksLike(String word) {
        String w = word.toLowerCase(Locale.ROOT);
        return !NOT_SURNAMES.contains(w) && ENDING.matcher(w.substring(w.lastIndexOf('-') + 1)).find();
    }
}
